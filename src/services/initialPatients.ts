export function getInitialPatients(): Patient[] {
  return realDatasetHoldoutCases.map((p) => {
    const prediction = predictPatientCardiacRisk(p.features);

    // Compute diagnostic concordance with ground-truth clinical diagnosis
    const isGroundTruthPositive = p.condition === 'Heart Disease';
    const isModelPositive = prediction.riskScore >= 50;
    let concordance: Patient['concordance'] = 'True Positive';
    if (isGroundTruthPositive && isModelPositive) concordance = 'True Positive';
    else if (!isGroundTruthPositive && !isModelPositive) concordance = 'True Negative';
    else if (!isGroundTruthPositive && isModelPositive) concordance = 'False Positive';
    else concordance = 'False Negative';

    // Baseline respiratory rate (breaths per min)
    const rr = p.target === 1 ? Math.round(18 + (p.seed % 5)) : Math.round(14 + (p.seed % 4));

    return {
      id: p.id,
      name: p.name,
      age: p.age,
      sex: p.sex,
      condition: p.condition,
      target: p.target,
      hr: p.hr,
      rr,
      spo2: p.spo2,
      bp: p.bp,
      risk: prediction.riskScore,
      state: prediction.state,
      concordance,
      seed: p.seed,
      updatedAt: Date.now() - Math.floor(Math.random() * 60000),
      features: p.features,
      shapExplanation: prediction.shapExplanation,
      limeExplanation: prediction.limeExplanation,
    };
  });
}
